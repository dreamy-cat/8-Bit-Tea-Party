; Глобальные имена, константы и описание структур графической библиотеки VGA,
;режим известынй как Mode-X, разрешение экрана 320 по горизонтали и 240 точек
;по вертикали. Палитра индексная в 256 определенных цветов, 6-бит компонетов.
; Статичные переменные, константные данные или вкод в этой версии пока не
;определены глобально, поэтому при включении данного файла размер не меняется.
; Но не исключается вынос глобальных данных, общих для всех процедур библиотеки.
; Формат портов, слово и данные в порт возможно отправляются как out dx,ax.
; Внимание! Библиотека тестировалась исключительно в DOSBox 0.74.3 и не
;предназначена для применения на реальном ретро-оборудовании, никаких гарантий!

; Рекомендуемые основные материалы и программы, подробнее в файле платформы.
; 1. IBM VGA/XGA Technical Reference Manual (Preliminary draft May 19th 1992).
; 2. Michael Abrash's Graphics Programming Black Book, Special Edition, 1997.
; 3. THelp 6.0 by Flambaux Software, Inc, 1994.
; 4. TWEAK 1.6c, by Robert Schmidt of Ztiff Zox Softwear, 1992-93.

; Общая конфигурация видеоадаптера VGA и режима X:
; - разрешение экрана 320*240 точек, 256 цветов по таблице индексов;
; - минимальный объем памяти видеоадаптера 256Кб, т.к. используются все 4
;плана по 64Кб каждый, от единого адреса 0A000h, только 64Кб недостаточно;
; - шина данных желательно 16-битная, работает и с 8-бит, но медленнее;
; - два бита цвета в каждом плане, тогда 4 плана * 2 бита = 8 бит, индекс цвета;
; - всего цветов по компонентам RGB(6-6-6) бит, всего 18бит или 256К цветов;
; - по возможности сверить и вынести индекс(названия) регистров здесь;
; - все регистры ввода-вывода и параметры адаптера VGA по стандарту 1992.

; Регистры общего назначения и статуса адаптера, используются только первые 3.
;Адрес ввода-вывода (бит 0), от него зависят порты B/D, см. в документации
;знаки вопроса. Оставлено для совместимости с MDA(CGA) монитором/адаптером.

VGA_MISC_WRITE          EQU 003C2h      ; Общие параметры вывода изображения,
VGA_MISC_READ           EQU 003CCh      ;синхронизации и адреса ввода-вывода.
VGA_INPUT_STATUS_0      EQU 003C2h      ; Состояние 0, прерывание и тип ЭЛТ.
VGA_INPUT_STATUS_1      EQU 003DAh      ; Состояние 1, обратный ход верт. луча.
VGA_CTRL_READ           EQU 003CAh      ; Следующие 4 регистра оставлены
VGA_CTRL_WRITE          EQU 003DAh      ;зарезервированными и не используются
VGA_SUBSYS_READ         EQU 003C3h      ;в коде.
VGA_SUBSYS_WRITE        EQU 003C3h

; Секвенсер адаптера. Генерирует базовые временные интервалы для видео памяти и
;характеристики такта(ов) для управления регенерацией буффера и его захвата.
; Это позволяет системе получать доступ к памяти во время активных интервалов
;отображения, пероидически вставляя выделенные системой циклы процессора между
;циклами(тактами) отрисовки.
; Все регистры секвенсера доступны для чтения и записи, кратко о регистрах
;от 000h до 004h: сбросж тактового режима; карта маски; набор символов;
;режим работы памяти.

VGA_SEQUENCER_ADDR      EQU 003C4h      ; Порты адреса и данных, допустимы
VGA_SEQUENCER_DATA      EQU 003C5h      ;команды записи сразу 16-бит.

; Модуль управления ЭЛТ адаптера, регистров очень много, поэтому оставлены
;только те, которые мы использовали в процедуре установки видеорежима.
; Контроллер генерирует горизонтальные и вертикальные временные сигналы для
;синхронизации видеопамяти. Адресация для регенирования буффера, курсора и
;другие параметры обновления ЭЛТ, см. документация 2-55.

VGA_CRT_ADDR            EQU 003D4h      ; Порты адреса и ригистра и порт для
VGA_CRT_DATA            EQU 003D5h      ;данных, биты должны сохранятся.
VGA_START_HIGH_ADDR     EQU 00Ch        ; Старшие и младшие 8-бит адреса
VGA_START_LOW_ADDR      EQU 00Dh        ;начала регенерации буффера, регистры.

; Графический контроллер это интерфейс между видео буффером и контроллером
;атрибутов на интервалах активного отображения, а также между видео памятью и
;процессором во время доступа к оперативной памяти.

VGA_GRAPHICS_ADDR       EQU 003CEh      ; Порт адреса регистра и порта данных,
VGA_GRAPHICS_DATA       EQU 003CFh      ;все регистры на чтение и запись.
VGA_GRAPH_DATA_ROTATE   EQU 003h        ; Регистр ротации данных или команды.

; Контроллер атрибутов берет данные из видеопамяти через графический контроллер
;и формирует их для отображения. Данные атрибутов в текстовом режиме и
;сериализация данных битовых планов в графическом режиме в 8-битные значение
;цвета на экране. В нашем коде не используется, оставим просто адреса портов.

VGA_ATTRIB_ADDR         EQU 003C0h      ; Регистр адреса для чтения/записи.
VGA_INT_PALETTE         EQU 003C1h      ; Внутренняя палитра, регистры.

; Видео цифровой-аналоговый преобразователь интегрирует функции цветовой
;палитры с тремя внутренними конвертерами для управления аналоговым сигналом
;дисплея. Он содержит 256 регистров-индексов, каждый из которых содержит
;18-бит, что позволяет отображать до 256 цветов из 256К возможных. Каждый
;преобразователь управляется 6-бит модулем. Общий алгоритм работы с палитрой:
;сначала записываем индекс цвета в 003C8h, затем последовательно 3 байта,
;в регистр данных 003C9h, из которых значимы только младшие 6 бит, итого 18 бит.
; Также регистр 003C7h в старших битах 6 и 7 содержит статус последней команды.

VGA_DAC_WRITE           EQU 003C8h      ; Адрес регистра индекса для записи.
VGA_DAC_READ            EQU 003C7h      ; Адрес регистра индекса для чтения.
VGA_DAC_DATA            EQU 003C9h      ; Адрес регистра данных, 3 байта.
VGA_PEL_MASK            EQU 003C6h      ; Дополнительная маска для пикселя.

; Общие константы связанные не только с VGA адаптером, но и с графикой в целом,
;сгруппировать и переименовать в следующей версии.
; Единственне глобальные данные для экрана, но позже возможны структуры.

GFX_SCR_ADDR            EQU 0A000h      ; Сегментный адрес графического экрана.
GFX_SCR_WIDTH           EQU 00140h      ; 320 точек по ширине, слово.
GFX_SCR_HEIGHT          EQU 000F0h      ; 240 точек по высоте, слово.
GFX_SCR_SIZE_B          EQU 000012C00h  ; Размер экрана в байтах, 76800.
GFX_SCR_SIZE_W          EQU 09600h      ; Размер экрана в словах, 38400.
GFX_SCR_SIZE_P          EQU 012C0h      ; Размер экрана в параграфах, 4800.
GFX_PLANE_SIZE_B        EQU 04B00h      ; Размер Х-плана в байтах, 19200.
GFX_PLANE_SIZE_W        EQU 02580h      ; Размер Х-плана в словах, 9600.
GFX_PLANE_SIZE_P        EQU 004B0h      ; Размер Х-плана в параграфах, 1200.
GFX_PLANES_MASK         EQU 00001111b   ; Общая маска для всех планов.
GFX_ALL_PAGES           EQU 003h        ; Всего страниц в режиме Х.
GFX_PAGE_SIZE_B         EQU 04B00h      ; Размер страницы в байтах, 19200.
GFX_PAGE_SIZE_W         EQU 02580h      ; Размер страницы в словах, 9600.
GFX_PAGE_SIZE_P         EQU 004B0h      ; Размер страницы в параграфах, 1200.
GFX_PAGE_0_OFFS         EQU 00000h      ; Смещение нулевой страницы.
GFX_PAGE_1_OFFS         EQU 04B00h      ; Первая страницы для режима 320*240.
GFX_PAGE_2_OFFS         EQU 09600h      ; Вторая страница для режима 320*240.
GFX_COLORS              EQU 00100h      ; Полные 256 цветов по таблице.
GFX_RGB_COLORS          EQU 040h        ; Различных цветов на компоненту, 64.
GFX_BPP                 EQU 008h        ; Количество бит на точку.
GFX_BPC                 EQU 006h        ; Количество бит на компонент цвета.
GFX_BYTES_PER_LINE      EQU 050h        ; Байт на каждую строчку пикселей.

